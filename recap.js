// In-memory store for previews (last 100).
const previews = new Map();
export const getPreview = (id) => previews.get(id);

export async function sendRecap(input) {
  const recap = buildRecap(input);
  const id = `${input.code}-${crypto.randomBytes(4).toString("hex")}`;
  if (previews.size >= 100) previews.delete(previews.keys().next().value);
  previews.set(id, { ...recap, userId: input.user?.id });

  const base = { guest_email: recap.to, preview_url: `/recap/${id}`, subject: recap.subject };
  if ((await getEmailSettings()).enabled) {
    // One key per booking and address: confirming twice doesn't mail twice.
    const idempotencyKey = crypto.createHash("sha256").update(`${input.code}|${recap.to}|${input.lang}`).digest("hex");
    const m = await sendEmail({ to: recap.to, subject: recap.subject, html: recap.html, text: recap.text, tag: "booking-recap", userId: input.user?.id, idempotencyKey });
    // A sandbox send is accepted by Telnyx but never delivered.
    return { ...base, sent: !m.sandbox, to: m.to, mode: m.sandbox ? "telnyx-sandbox" : "telnyx", message_id: m.id };
  }
  const to = overrideTo() || recap.to;
  let sent = false;
  if (smtp()) {
    await smtp().sendMail({ from: from(), to, subject: recap.subject, html: recap.html, text: recap.text });
    sent = true;
  }
  return { ...base, sent, to, mode: smtp() ? "smtp" : "preview" };
}
