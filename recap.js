const fail = (message) => { throw Object.assign(new Error(message), { status: 400 }); };

// The checks the e-mail and the SMS share: code, guest name, and a stay that
// is still valid and available (recomputed here, never trusted from the browser).
function checkBooking(booking, code) {
  if (!CODE_RE.test(String(code))) fail("invalid booking code");
  const name = clean(booking.guest_name, 80);
  if (!name) fail("guest name is required");
  const avail = Booking.checkAvailability(booking);
  if (!avail.ok) fail(avail.errors.join("; "));
  const room = avail.rooms.find((r) => r.room_type === booking.room_type);
  if (!room?.available) fail("room not available");
  return { name, avail, room };
}

// Booking confirmation SMS text in the guest's language. Throws like buildRecap.
export function buildSms({ booking = {}, code, lang }) {
  const t = T[lang] || T.en;
  const { avail, room } = checkBooking(booking, code);
  const fmt = (iso) => Booking.parseISO(iso).toLocaleDateString(t.locale, { day: "numeric", month: "short" });
  const eur = new Intl.NumberFormat(t.locale, { style: "currency", currency: "EUR", maximumFractionDigits: 0 }).format(room.total_eur);
  return t.sms(code, avail.hotel_name, fmt(booking.check_in), fmt(booking.check_out), room.name, eur);
}

// The booking as short English facts, for a WhatsApp template's parameters
// (approved templates are fixed text; these fill its {{1}}, {{2}}, …).
export function bookingFacts({ booking = {}, code }) {
  const { name, avail, room } = checkBooking(booking, code);
  const fmt = (iso) => Booking.parseISO(iso).toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" });
  return {
    guest: name,
    title: `${room.name} · booking ${code}`,
    hotel: avail.hotel_name,
    dates: `${fmt(booking.check_in)} – ${fmt(booking.check_out)} (${avail.nights} ${avail.nights === 1 ? "night" : "nights"})`,
    time: "Check-in from 15:00",
  };
}

