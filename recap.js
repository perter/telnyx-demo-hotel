// What happens to a recap while Telnyx Email is off.
export function recapMode() {
  if (!smtp()) return "preview only (no SMTP_HOST)";
  return overrideTo() ? `SMTP, all recaps redirected to ${overrideTo()}` : "SMTP";
}

