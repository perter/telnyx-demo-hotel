// Read lazily: server.js loads .env after its imports have run.
let transport;
function smtp() {
  if (transport === undefined) {
    transport = setting("SMTP_HOST")
      ? nodemailer.createTransport({
          host: setting("SMTP_HOST"),
          port: Number(setting("SMTP_PORT") || 587),
          secure: Number(setting("SMTP_PORT")) === 465,
          auth: setting("SMTP_USER") ? { user: setting("SMTP_USER"), pass: setting("SMTP_PASS") } : undefined,
        })
      : null;
  }
  return transport;
}
